import com.ai.tinymodels.domain.model.AppTheme

fun colorSchemeFor(theme: AppTheme, darkTheme: Boolean): ColorScheme = when (theme) {
    AppTheme.DEFAULT -> if (darkTheme) darkScheme else lightScheme
    AppTheme.GITHUB -> if (darkTheme) githubDarkScheme else githubLightScheme
    AppTheme.VERCEL -> if (darkTheme) vercelDarkScheme else vercelLightScheme
    AppTheme.NIGHT_OWL -> if (darkTheme) nightOwlDarkScheme else nightOwlLightScheme
    AppTheme.DRACULA -> if (darkTheme) draculaDarkScheme else draculaLightScheme
    AppTheme.NORD -> if (darkTheme) nordDarkScheme else nordLightScheme
    AppTheme.CATPPUCCIN -> if (darkTheme) catppuccinDarkScheme else catppuccinLightScheme
}

